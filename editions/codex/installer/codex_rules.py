#!/usr/bin/env python3
"""Write a Codex rules file that lets headless Blender run the kit's own scripts outside the sandbox.

Why: on macOS, Blender crashes inside the Codex sandbox (the sandbox blocks the Metal GPU check),
so every model check and every 3D tool fails there. The rule allows only these literal commands:
  <Blender> -b --python <installed kit script>.py ...
  <Blender> -b --python-exit-code 1 --python <installed kit script>.py ...
  <3D venv python> <sweep.py | apply_edit.py | preflight.py> ...   (they start Blender themselves)
Any other Blender or Python command still runs in the sandbox or asks the user.
The skills folder is read-only inside the sandbox, so an agent cannot change the allowed scripts.

Usage (run outside Codex, after the skills are installed):
  python3 installer/codex_rules.py            # preview the file, write nothing
  python3 installer/codex_rules.py --write    # write ~/.codex/rules/zps-art-assets-kit.rules
Options: --skills-root (default ~/.agents/skills), --blender, --rules-dir (default $CODEX_HOME/rules).
Run it again after each upgrade: the file lists the installed scripts. Restart Codex after writing."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

MARK = '# Generated by ZPS Art Assets Kit installer/codex_rules.py. Regenerate after each upgrade.'
FILE = 'zps-art-assets-kit.rules'
MAC_BLENDER = '/Applications/Blender.app/Contents/MacOS/Blender'
SPAWNERS = ['tools/optimize/sweep.py', 'tools/self_build/apply_edit.py', 'tools/preflight.py']


def find_blender(given):
    for p in (given, os.environ.get('BLENDER'), MAC_BLENDER, shutil.which('blender')):
        if p and os.path.isfile(p) and os.access(p, os.X_OK):
            return os.path.realpath(p) if os.path.islink(p) else p
    return None


# Scripts that call paid network APIs. They must never match the allow rule: Codex has to ask
# before each of them runs outside the sandbox (network on).
NETWORK_SCRIPTS = ('gen_api.py', 'generate_image.py')


def network_scripts(root):
    return [str(p) for p in sorted(root.rglob('*.py')) if p.name in NETWORK_SCRIPTS and '.deps' not in p.parts]


def kit_scripts(root):
    out = []
    for base in sorted(root.glob('zps-*-codex')) + [root / '.art-production-support']:
        for p in sorted(base.rglob('*.py')):
            if '.deps' not in p.parts and '__pycache__' not in p.parts and p.name not in NETWORK_SCRIPTS:
                out.append(str(p))
    return out


def q(s):
    return json.dumps(s)


def render(blender, scripts, venv_py, skill3d):
    lines = [MARK, '']
    alts = '[\n        ' + ',\n        '.join(q(s) for s in scripts) + ',\n    ]'
    why = 'ZPS Art Assets Kit: Blender crashes inside the Codex sandbox on macOS (Metal GPU check). Allow headless Blender to run only the installed kit scripts.'
    for prefix in (['-b', '--python'], ['-b', '--python-exit-code', '1', '--python']):
        head = ', '.join(q(x) for x in [blender] + prefix)
        lines += [f'prefix_rule(\n    pattern = [{head}, {alts}],\n    decision = "allow",\n    justification = {q(why)},\n)', '']
    if venv_py:
        sp = '[' + ', '.join(q(str(skill3d / s)) for s in SPAWNERS) + ']'
        lines += [f'prefix_rule(\n    pattern = [{q(str(venv_py))}, {sp}],\n    decision = "allow",\n'
                  f'    justification = {q("ZPS Art Assets Kit: these 3D tools start Blender themselves, so they must run outside the sandbox.")},\n)', '']
    return '\n'.join(lines)


def self_test(path, blender, scripts, venv_py, skill3d, root):
    codex = shutil.which('codex')
    if not codex:
        return 'codex CLI not found: rule not tested'
    cases = [([blender, '-b', '--python', scripts[0], '--', 'x'], 'allow'),
             ([blender, '-b', '--python-exit-code', '1', '--python', scripts[-1], '--'], 'allow'),
             ([blender, '-b', '--python-expr', 'print(1)'], None),
             ([blender, '-b', '--python', '/tmp/other.py'], None)]
    cases += [([blender, '-b', '--python', n, '--', 'generate'], None) for n in network_scripts(root)]
    if venv_py:
        cases.append(([str(venv_py), str(skill3d / SPAWNERS[0]), '--work', 'w'], 'allow'))
        cases.append(([str(venv_py), '-c', 'print(1)'], None))
    bad = []
    for cmd, want in cases:
        r = subprocess.run([codex, 'execpolicy', 'check', '--rules', str(path), '--', *cmd], capture_output=True, text=True)
        got = json.loads(r.stdout or '{}').get('decision')
        if got != want:
            bad.append(f'{cmd[:4]} -> {got}, expected {want}')
    return 'rule test passed' if not bad else 'RULE TEST FAILED: ' + '; '.join(bad)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--skills-root', type=Path, default=Path('~/.agents/skills'))
    ap.add_argument('--blender')
    ap.add_argument('--rules-dir', type=Path, default=Path(os.environ.get('CODEX_HOME', '~/.codex')) / 'rules')
    ap.add_argument('--write', action='store_true')
    a = ap.parse_args()
    root = a.skills_root.expanduser().resolve()
    blender = find_blender(a.blender)
    if not blender:
        print('Blender not found. Install it or pass --blender /path/to/Blender.'); return 2
    scripts = kit_scripts(root)
    if not scripts:
        print(f'No installed kit scripts in {root}. Install the Codex edition first.'); return 2
    skill3d = root / 'zps-3d-artist-codex'
    venv_py = skill3d / 'tools/.deps/venv/bin/python'
    if not venv_py.exists():
        print(f'Note: {venv_py} does not exist yet. Run setup_deps.sh, then run this script again.')
        venv_py = None
    text = render(blender, scripts, venv_py, skill3d)
    target = a.rules_dir.expanduser() / FILE
    tmp = Path(os.environ.get('TMPDIR', '/tmp')) / f'{FILE}.preview'
    tmp.write_text(text)
    result = self_test(tmp, blender, scripts, venv_py, skill3d, root)
    print(f'Blender: {blender}\nKit scripts: {len(scripts)}\n3D venv rule: {"yes" if venv_py else "no"}\n{result}')
    if 'FAILED' in result:
        return 1
    if not a.write:
        print(f'Preview only: {tmp}\nRun with --write to install it as {target}.'); return 0
    if target.exists() and MARK not in target.read_text():
        print(f'{target} exists and was not written by this kit. Nothing written.'); return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    print(f'Wrote {target}. Restart Codex to load it.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
